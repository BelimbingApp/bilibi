-- Identity/contact storage only. Accounts and affiliation links are optional,
-- owned by User and Affiliation respectively, and never created by this table.
CREATE TABLE persons (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL REFERENCES tenants(id),
    name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 160),
    kind text NOT NULL CHECK (kind IN ('human', 'agent')),
    email text CHECK (email IS NULL OR (octet_length(email) BETWEEN 1 AND 254 AND email ~ '^[^[:space:]@]+@[^[:space:]@]+$')),
    phone text CHECK (phone IS NULL OR length(phone) BETWEEN 1 AND 64),
    system_key text CHECK (system_key IS NULL OR system_key = 'platform-orchestrator'),
    retired_at timestamptz,
    version bigint NOT NULL DEFAULT 1 CHECK (version >= 1),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, id),
    UNIQUE (system_key),
    CHECK (system_key IS NULL OR (kind = 'agent' AND retired_at IS NULL))
);
-- Deliberately non-unique: contacts with the same email/name are candidates,
-- never automatically merged and never confused with unique login accounts.
CREATE INDEX persons_name ON persons (tenant_id, lower(name), id);
CREATE INDEX persons_email ON persons (tenant_id, lower(email)) WHERE email IS NOT NULL;
CREATE INDEX persons_phone ON persons (tenant_id, phone) WHERE phone IS NOT NULL;
